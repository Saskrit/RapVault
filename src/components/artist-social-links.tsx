type ArtistSocialLinksProps = {
  links: Partial<SocialLinks>;
  className?: string;
};

export function ArtistSocialLinks({
  links,
  className = "",
}: ArtistSocialLinksProps) {
  const items = SOCIAL_LINK_META.filter((item) => links[item.key]?.trim());
  if (items.length === 0) return null;

  return (
    <div className={`flex flex-wrap items-center gap-2 ${className}`}>
      {items.map((item) => (
        <a
          key={item.key}
          href={links[item.key]}
          target="_blank"
          rel="noopener noreferrer"
          className="inline-flex h-10 w-10 items-center justify-center rounded-xl border border-border bg-background text-muted transition hover:border-accent hover:text-accent"
          aria-label={item.label}
          title={item.label}
        >
          {ICONS[item.key]}
        </a>
      ))}
    </div>
  );
}
